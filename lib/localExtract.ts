const MIN_TAGS = 4;
const MAX_TAGS = 7;

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function compile(triggers: Record<string, string[]>): Record<string, RegExp[]> {
  const compiled: Record<string, RegExp[]> = {};
  for (const [tag, words] of Object.entries(triggers)) {
    // The optional s/es suffix lets one entry cover "model"/"models", "pitch"/"pitches".
    compiled[tag] = words.map(
      (word) => new RegExp(`\\b${escapeRegExp(word)}(?:e?s)?\\b`, "i"),
    );
  }
  return compiled;
}

const COMPILED_SKILLS = compile(SKILL_TRIGGERS);
const COMPILED_INTERESTS = compile(INTEREST_TRIGGERS);

function pickTags(
  text: string,
  vocab: string[],
  compiled: Record<string, RegExp[]>,
  fallbacks: string[],
): string[] {
  const hits = vocab
    .map((tag, order) => ({
      tag,
      order,
      count: (compiled[tag] ?? []).filter((re) => re.test(text)).length,
    }))
    .filter((entry) => entry.count > 0)
    .sort((a, b) => b.count - a.count || a.order - b.order);

  const picked = hits.slice(0, MAX_TAGS).map((entry) => entry.tag);

  for (const fallback of fallbacks) {
    if (picked.length >= MIN_TAGS) break;
    if (!picked.includes(fallback)) picked.push(fallback);
  }

  return picked;
}

export function localExtract(text: string): {
  softSkills: string[];
  interests: string[];
} {
  const input = text ?? "";
  return {
    softSkills: pickTags(
      input,
      TAG_VOCAB.softSkills,
      COMPILED_SKILLS,
      SKILL_FALLBACKS,
    ),
    interests: pickTags(
      input,
      TAG_VOCAB.interests,
      COMPILED_INTERESTS,
      INTEREST_FALLBACKS,
    ),
  };
}
